// 执行实际页面函数，检查正式参数展示和自定义预算的往返恢复。
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const path=require('node:path');
const folder=process.argv[2];
const elements=new Map();
const get=id=>{
  if(!elements.has(id))elements.set(id,{value:'1',checked:false,disabled:false,type:'number'});
  return elements.get(id);
};
const context=vm.createContext({structuredClone,console,document:{getElementById:get}});
vm.runInContext(fs.readFileSync(path.join(folder,'workspace.js'),'utf8'),context);
vm.runInContext(fs.readFileSync(path.join(folder,'app.js'),'utf8').replace('\ninit();\n','\n'),context);
const profile=JSON.parse(fs.readFileSync(path.join(folder,'../formal_profile.json'),'utf8'));
context.profile=profile;
const run=code=>vm.runInContext(code,context);
run(`boot={training_profile:profile};$('targetKind').value='chart-image';$('speedPriority').value='standard';$('searchStarts').value='3';$('wbTraining').checked=true;trainingModeHint();`);
assert.equal(get('searchStarts').value,12);
assert.equal(get('searchStarts').disabled,true);
assert.equal(get('wbTraining').checked,false);
assert.match(get('trainingModeHint').textContent,/网格 5 轮/);
run(`$('speedPriority').value='custom';trainingModeHint();`);
assert.equal(get('searchStarts').value,'3');
assert.equal(get('wbTraining').checked,true);
assert.equal(get('searchStarts').disabled,false);
assert.equal(run('workspaceTrainingOptions().speedPriority'),'custom');
run('busy=true;trainingModeHint();');
assert.equal(get('searchStarts').disabled,true);
run(`busy=false;$('targetKind').value='lut';$('speedPriority').value='standard';trainingModeHint();`);
assert.equal(run('formalTraining()'),false);
assert.equal(get('searchStarts').disabled,false);
run(`workspace={id:'eeeeeeeeeeeeeeeeeeeeeeeeeeeeeeee'};draft={short_name:'测试',full_name:'测试滤镜'};`);
assert.equal(run('fitOptions(true).project_id'),'eeeeeeeeeeeeeeeeeeeeeeeeeeeeeeee');
assert.equal(run('typeof qualitySummary'),'function');
assert.match(run("qualitySummary({adopted:false,baseline_identity:{},photo_scope:'not-bound'})"),/保留.*配方/);
assert.match(run("qualitySummary({adopted:true,photo_scope:'development-and-holdout'})"),/照片/);
assert.equal(run("gridLimitFraction({payload_hex:'c0003f01',fitting:{}})"),.5);
console.log(JSON.stringify({status:'PASS',scenarios:8}));
